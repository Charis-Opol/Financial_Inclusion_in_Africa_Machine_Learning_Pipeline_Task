"""Counts finished folds for every Phase 4 arm and writes week4/results/phase4_completion.md.

  week4/.venv/bin/python week4/src/completion.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from harness import N_OUTER, RunConfig  # noqa: E402
from run_all import EXPERIMENTS  # noqa: E402
from run_record import RESULTS_DIR  # noqa: E402

SEEDS = range(5)
N_COUNTRIES = 4


def main() -> int:
    config = RunConfig()
    rows, missing = [], 0
    for experiment, (design, arms) in EXPERIMENTS.items():
        expected = len(SEEDS) * (N_OUTER if design == "nested" else N_COUNTRIES)
        for arm in arms:
            metas = sorted((config.output_dir / design / arm).glob("seed*/*.json"))
            records = [json.loads(p.read_text(encoding="utf-8")) for p in metas]
            hours = sum(r["seconds"] for r in records) / 3600
            devices = sorted({r["device"] for r in records})
            missing += expected - len(records)
            rows.append(f"| {experiment} | {design} | {arm} | {len(records)} / {expected} | {hours:.2f} | {', '.join(devices)} |")
    text = "\n".join(
        [
            "# Phase 4 completion",
            "",
            "Generated by `week4/src/completion.py` from `results/oof/`. Hours are summed fold times.",
            "",
            "| Experiment | Design | Arm | Folds finished | Hours | Device |",
            "|---|---|---|---|---|---|",
            *rows,
            "",
            f"Folds still missing: {missing}.",
        ]
    )
    (RESULTS_DIR / "phase4_completion.md").write_text(text + "\n", encoding="utf-8")
    print(text)
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
